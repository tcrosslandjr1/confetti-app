// Confetti Outing Category System v2
// Universal taxonomy: 150+ outing categories across 12 groups with metadata
// that drives vibe mapping, venue filtering, safety rules, and city logic.

export type WaterfrontRelevance = "none" | "optional" | "preferred" | "required";
export type Intensity = "low" | "medium" | "high";

export type CategoryGroupId =
  | "social"
  | "nightlife"
  | "chill"
  | "food"
  | "culture"
  | "adventure"
  | "action"
  | "luxury"
  | "wellness"
  | "shopping"
  | "local"
  | "custom";

export type OutingCategory = {
  id: string;
  name: string;
  group: CategoryGroupId;
  description: string;
  defaultVibes: string[];
  compatibleVibes: string[];
  venueTypes: string[];
  activityTypes: string[];
  budgetTiers: (1 | 2 | 3 | 4)[];
  idealGroupSize: [number, number];
  waterfront: WaterfrontRelevance;
  familySafe: boolean;
  adultOnly: boolean;
  nightlifeIntensity: Intensity;
  conversationFriendly: boolean;
  weatherSensitive: boolean;
  seasonal: boolean;
  /** Hard guardrails: enforced filters when this category is in the request. */
  safetyFilters: string[];
  /** Venue types that must NEVER appear with this category. */
  avoidVenueTypes: string[];
  /** Slot blueprint hints for the planner (e.g. "Pre", "Main", "Late"). */
  suggestedSlots: string[];
};

