export const CATEGORIES_BY_ID: Record<string, OutingCategory> = Object.fromEntries(
  OUTING_CATEGORIES.map((c) => [c.id, c]),
);

export function categoriesInGroup(group: CategoryGroupId): OutingCategory[] {
  return OUTING_CATEGORIES.filter((c) => c.group === group);
}

/**
 * Merge a set of selected categories into a single resolved constraint set
 * the planner can use as a directive.
 */
export type ResolvedConstraints = {
  categoryIds: string[];
  categoryNames: string[];
  vibeTags: string[];
  venueTypes: string[];
  avoidVenueTypes: string[];
  safetyFilters: string[];
  budgetTiers: (1 | 2 | 3 | 4)[];
  groupSize: [number, number];
  waterfront: WaterfrontRelevance;
  familySafe: boolean;
  adultOnly: boolean;
  conversationFriendly: boolean;
  weatherSensitive: boolean;
};

const WATER_RANK: Record<WaterfrontRelevance, number> = {
  none: 0,
  optional: 1,
  preferred: 2,
  required: 3,
};

export function resolveCategories(ids: string[]): ResolvedConstraints | null {
  const cats = ids.map((id) => CATEGORIES_BY_ID[id]).filter(Boolean);
  if (!cats.length) return null;

  const setOf = (arr: string[][]) => Array.from(new Set(arr.flat()));
  const groupMin = Math.max(...cats.map((c) => c.idealGroupSize[0]));
  const groupMax = Math.min(...cats.map((c) => c.idealGroupSize[1]));
  const waterfront = cats.reduce<WaterfrontRelevance>(
    (acc, c) => (WATER_RANK[c.waterfront] > WATER_RANK[acc] ? c.waterfront : acc),
    "none",
  );

  return {
    categoryIds: cats.map((c) => c.id),
    categoryNames: cats.map((c) => c.name),
    vibeTags: setOf([cats.map((c) => c.defaultVibes).flat()]),
    venueTypes: setOf([cats.map((c) => c.venueTypes).flat()]),
    avoidVenueTypes: setOf([cats.map((c) => c.avoidVenueTypes).flat()]),
    safetyFilters: setOf([cats.map((c) => c.safetyFilters).flat()]),
    budgetTiers: setOf([cats.map((c) => c.budgetTiers.map(String)).flat()]).map(
      (n) => Number(n) as 1 | 2 | 3 | 4,
    ),
    groupSize: [groupMin, Math.max(groupMin, groupMax)],
    waterfront,
    familySafe: cats.every((c) => c.familySafe),
    adultOnly: cats.some((c) => c.adultOnly),
    conversationFriendly: cats.some((c) => c.conversationFriendly),
    weatherSensitive: cats.some((c) => c.weatherSensitive),
  };
}

/**
 * Build a single directive string the planner can append to the LLM prompt.
 * Promo-safe: never mentions sponsorship or paid placement.
 */
export function buildCategoryDirective(c: ResolvedConstraints, freeText?: string): string {
  const parts: string[] = [];
  parts.push(`outing categories: ${c.categoryNames.join(" + ")}`);
  if (freeText?.trim()) parts.push(`user said: "${freeText.trim().slice(0, 200)}"`);
  if (c.vibeTags.length) parts.push(`vibe tags: ${c.vibeTags.join(", ")}`);
  if (c.venueTypes.length)
    parts.push(`prefer venue types: ${c.venueTypes.slice(0, 18).join(", ")}`);
  if (c.avoidVenueTypes.length) parts.push(`AVOID venue types: ${c.avoidVenueTypes.join(", ")}`);
  if (c.safetyFilters.length) parts.push(`hard safety filters: ${c.safetyFilters.join(", ")}`);
  if (c.familySafe)
    parts.push("must be family-safe (no clubs, strip clubs, heavy drinking, adult entertainment)");
  if (c.adultOnly) parts.push("21+ only");
  if (c.conversationFriendly)
    parts.push("must be conversation-friendly (no loud clubs / dive bars)");
  if (c.waterfront === "required") parts.push("waterfront is required");
  else if (c.waterfront === "preferred")
    parts.push("prefer waterfront, else scenic alternative (rooftop, overlook, skyline, garden)");
  return parts.join("; ");
}
