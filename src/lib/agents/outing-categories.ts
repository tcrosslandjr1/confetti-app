function cat(
  input: Partial<OutingCategory> &
    Pick<OutingCategory, "id" | "name" | "group" | "description" | "defaultVibes" | "venueTypes">,
): OutingCategory {
  return {
    ...DEFAULTS,
    compatibleVibes: input.defaultVibes,
    activityTypes: input.activityTypes ?? input.venueTypes,
    ...input,
  } as OutingCategory;
}

